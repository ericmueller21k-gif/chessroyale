import { BOSS_KITS, RECLUSE_CHILD_KIT, artOf, type BossKit } from "../src/characters/kits.ts";
import { renderFrame } from "../src/characters/sprite.ts";
import { CHILD_FORM, FINAL_FORM } from "../src/characters/portraits.ts";
import { RECLUSE, coatFrame } from "../src/characters/recluse.ts";

/**
 * The Hidden Boss in his final form (the four boards; recluse.ts `coatFrame`, as BossCharacter draws him from his transformation on): his
 * phase-2 idle's first frame in the coat, the man's portrait window. Only for its portrait (the profile's match history, Nov 26).
 */
function finalFormKit(): BossKit {
  const man = BOSS_KITS["Hidden Boss"]!;
  const ch = { ...RECLUSE, anims: { idle: { loop: true, frames: [coatFrame(RECLUSE.anims.idle2!.frames[0]!)] } } };
  return { ...man, ch, sprite: undefined, portrait: { ...man.portrait, anim: "idle", frame: 0 } };
}

/**
 * Every boss's portrait frame (`BossKit.portrait`'s animation and frame, as drawn: `artOf`), as pixels small enough for the first load
 * (characters/portraits.ts): what home, the boss select's tiles and the menus draw without loading a boss's own code. The test
 * (portraits.test.ts) checks characters/portraits.gen.ts against this; `npx tsx packages/app/scripts/portraits.ts` writes it again after a
 * change to a boss's drawing or portrait.
 */
let finalKit: BossKit | undefined;
export function portraitEntries(): [string, BossKit][] {
  return [...Object.entries(BOSS_KITS), [CHILD_FORM, RECLUSE_CHILD_KIT], [FINAL_FORM, (finalKit ??= finalFormKit())]];
}

/** Palette keys, one character each (no digit: a run's count follows its key; "." is an empty pixel). */
const KEYS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz!#$%&()*+,-/:;<=>?@[]^_{|}~";

/** One portrait as the generated file holds it: its frame's size, the face's window, its colors and its pixels (run-length). */
export function encodePortrait(kit: BossKit): { w: number; h: number; face: readonly [number, number, number, number]; pal: string; px: string } {
  const art = artOf(kit);
  const p = kit.portrait;
  const frame = art.anims[p.anim]!.frames[p.frame]!;
  const { w, h, data } = renderFrame(art, frame);
  const pal: string[] = [];
  const index = new Map<string, number>();
  let px = "";
  let last = "";
  let run = 0;
  const flush = () => {
    if (run) px += last + (run > 1 ? String(run) : "");
  };
  for (let i = 0; i < w * h; i++) {
    const a = data[i * 4 + 3]!;
    let key = ".";
    if (a) {
      const c = [0, 1, 2, 3].map((j) => data[i * 4 + j]!.toString(16).padStart(2, "0")).join("");
      let k = index.get(c);
      if (k === undefined) {
        k = pal.length;
        if (k >= KEYS.length) throw new Error(`${art.id}: more than ${KEYS.length} colors in its portrait`);
        index.set(c, k);
        pal.push(c);
      }
      key = KEYS[k]!;
    }
    if (key === last) run++;
    else {
      flush();
      last = key;
      run = 1;
    }
  }
  flush();
  return { w, h, face: [p.x, p.y, p.w, p.h], pal: pal.join(""), px };
}

/** The generated file's text. */
export function portraitsSource(): string {
  const rows = portraitEntries().map(([name, kit]) => `  ${JSON.stringify(name)}: ${JSON.stringify(encodePortrait(kit))},`);
  return [
    "// Generated by packages/app/scripts/portraits.ts from each boss's drawing (test/portraits-make.ts): don't edit; run it again after a",
    "// change to a boss's drawing or portrait (portraits.test.ts fails until then).",
    'import type { PortraitData } from "./portraits.ts";',
    "",
    "export const PORTRAITS: Readonly<Record<string, PortraitData>> = {",
    ...rows,
    "};",
    "",
  ].join("\n");
}
