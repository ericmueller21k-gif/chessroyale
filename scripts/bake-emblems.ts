/**
 * Bakes ranked 1 v 1's emblems (packages/app/src/characters/rank-set.ts, the set Eric approved on Oct 28, copied as
 * drawn) into one picture, `packages/app/src/emblems/rank-emblems.png`, with where each emblem sits in it in
 * `packages/app/src/emblems/rank-emblems.ts` (both generated; don't edit them by hand). The same way as the sidekicks
 * (scripts/bake-sidekicks.ts): no art code runs on a phone, the screens show a cut of one small picture.
 *
 * The sheet: a row per tier with divisions (Wood … Radiant), its divisions 5 to 1 left to right; then a row per top
 * tier (Pearlescent, Transcendent), its loop's frames left to right. 48 × 48 pixels a frame. With it, each emblem's
 * place, its frames' times, and a hash of every frame's pixels, which `packages/app/test/rank-emblems.test.ts` checks
 * against the drawing, so the sheet can't go stale.
 *
 * Run after changing the drawing: `npx tsx scripts/bake-emblems.ts`.
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { RANKED_1V1, emblemId } from "../packages/core/src/index.ts";
import { RANK_SET } from "../packages/app/src/characters/rank-set.ts";
import { renderFrame, type Character } from "../packages/app/src/characters/sprite.ts";
import { png } from "./bake-sidekicks.ts";

const OUT = "packages/app/src/emblems/rank-emblems.ts";
const PNG = "packages/app/src/emblems/rank-emblems.png";

/** Every emblem's animation name in the drawing, row by row as the sheet has them. */
export function emblemRows(): string[][] {
  const R = RANKED_1V1;
  const divisions = Array.from({ length: R.divisions }, (_, i) => R.divisions - i);
  return [...R.tiers.map((t) => divisions.map((d) => emblemId(t.name, d))), ...R.topTiers.map((t) => [emblemId(t.name, null)])];
}

/** A hash of every emblem's frames' pixels, in the sheet's order (the test recomputes it from the drawing). */
export function emblemHash(ch: Character = RANK_SET): string {
  const h = createHash("sha256");
  for (const id of emblemRows().flat()) for (const f of ch.anims[id]!.frames) h.update(renderFrame(ch, f).data);
  return h.digest("hex").slice(0, 16);
}

function main() {
  const ch = RANK_SET;
  const rows = emblemRows();
  // (A still is one frame; a loop's frames go along its row.)
  const cols = Math.max(...rows.map((r) => (r.length > 1 ? r.length : ch.anims[r[0]!]!.frames.length)));
  const W = cols * ch.w;
  const H = rows.length * ch.h;
  const sheet = new Uint8Array(W * H * 4);
  const entries: string[] = [];
  const put = (data: Uint8ClampedArray, row: number, col: number) => {
    for (let y = 0; y < ch.h; y++) sheet.set(data.subarray(y * ch.w * 4, (y + 1) * ch.w * 4), ((row * ch.h + y) * W + col * ch.w) * 4);
  };
  rows.forEach((ids, row) => {
    if (ids.length > 1) {
      ids.forEach((id, col) => {
        const frames = ch.anims[id]!.frames;
        if (frames.length !== 1) throw new Error(`${id}: a division's emblem is one still`);
        put(renderFrame(ch, frames[0]!).data, row, col);
        entries.push(`  ${JSON.stringify(id)}: { x: ${col * ch.w}, y: ${row * ch.h}, frames: 1, ms: ${frames[0]!.ms} },`);
      });
      return;
    }
    const id = ids[0]!;
    const frames = ch.anims[id]!.frames;
    const ms = frames[0]!.ms;
    if (frames.some((f) => f.ms !== ms)) throw new Error(`${id}: the loop's frames must share one time`);
    frames.forEach((f, col) => put(renderFrame(ch, f).data, row, col));
    entries.push(`  ${JSON.stringify(id)}: { x: 0, y: ${row * ch.h}, frames: ${frames.length}, ms: ${ms} },`);
  });
  mkdirSync("packages/app/src/emblems", { recursive: true });
  const pic = png(W, H, sheet);
  writeFileSync(PNG, pic);
  writeFileSync(
    OUT,
    `// Generated by scripts/bake-emblems.ts from packages/app/src/characters/rank-set.ts: don't edit by hand
// (npx tsx scripts/bake-emblems.ts). The sheet is ./rank-emblems.png: a row per tier with divisions (5 to 1, left to
// right), then a row per top tier (its loop's frames, left to right); ${ch.w} x ${ch.h} pixels a frame.

/** One emblem in the sheet: its first frame's top left, its frames (along the row) and each frame's time (ms). */
export interface EmblemCell {
  x: number;
  y: number;
  frames: number;
  ms: number;
}

/** A frame's size in the sheet (CSS pixels at 1×), and the sheet's. */
export const EMBLEM_SIZE = ${ch.w};
export const EMBLEM_SHEET = { w: ${W}, h: ${H} } as const;

/** A hash of every frame's pixels (packages/app/test/rank-emblems.test.ts checks it against the drawing). */
export const EMBLEM_HASH = "${emblemHash(ch)}";

export const EMBLEMS: Readonly<Record<string, EmblemCell>> = {
${entries.join("\n")}
};
`,
  );
  console.log(`${PNG}: ${W} x ${H}, ${(pic.length / 1024).toFixed(1)} KB, ${entries.length} emblems`);
}

if (process.argv[1]?.endsWith("bake-emblems.ts")) main();
