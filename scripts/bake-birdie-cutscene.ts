/**
 * Bakes Birdie's fall's cutscene (packages/app/src/characters/birdie-cutscene-fall.ts and birdie-cutscene-armored.ts, the art as drawn)
 * into one picture for the game: `packages/app/src/characters/birdie-cutscene.png`, with what the cutscene needs to play it in
 * `packages/app/src/characters/birdie-cutscene-sheet.ts` (both generated; don't edit them by hand).
 *
 * Why (docs/decisions/2026-11-23-birdie-fall.md): the two drawings' code paints its full-screen parts as it's first read, about 0.9 s and
 * 0.4 s of a fast core (measured), a long task a phone would feel in the middle of the battle. Baked, the cutscene is one small picture,
 * decoded as his battle starts, as Moo's Full Moon's (characters/moo-cinematic.png). The sheet is one row: the fall's frames, the
 * approach's, the reveal's, then the hold's, each 200 x 260; with each animation, its first frame's column and its frames' times; and a
 * hash of every frame's pixels, which `packages/app/test/birdie.test.ts` checks against the drawings, so the sheet can't go stale.
 *
 * Run after changing either drawing: `npx tsx scripts/bake-birdie-cutscene.ts`.
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { deflateSync } from "node:zlib";
import { renderFrame, type Character } from "../packages/app/src/characters/sprite.ts";
import { ARENA_BIRDIE_FALL } from "../packages/app/src/characters/birdie-cutscene-fall.ts";
import { ARENA_BIRDIE_ARMORED } from "../packages/app/src/characters/birdie-cutscene-armored.ts";

const OUT = "packages/app/src/characters/birdie-cutscene-sheet.ts";
const PNG = "packages/app/src/characters/birdie-cutscene.png";

/** The sheet's animations in order: each from its drawing. */
export const CUTSCENE_ANIMS = [
  [ARENA_BIRDIE_FALL, "fall"],
  [ARENA_BIRDIE_FALL, "approach"],
  [ARENA_BIRDIE_ARMORED, "reveal"],
  [ARENA_BIRDIE_ARMORED, "hold"],
] as const satisfies readonly (readonly [Character, string])[];

/** A hash of the sheet's frames' pixels, in its order (the test recomputes it from the drawings). */
export function cutsceneHash(): string {
  const h = createHash("sha256");
  for (const [ch, a] of CUTSCENE_ANIMS) for (const f of ch.anims[a]!.frames) h.update(renderFrame(ch, f).data);
  return h.digest("hex").slice(0, 16);
}

const CRC = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = (buf: Uint8Array) => {
  let c = 0xffffffff;
  for (const b of buf) c = CRC[(c ^ b) & 255]! ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
const chunk = (type: string, body: Uint8Array) => {
  const out = Buffer.alloc(12 + body.length);
  out.writeUInt32BE(body.length, 0);
  out.write(type, 4, "ascii");
  Buffer.from(body).copy(out, 8);
  out.writeUInt32BE(crc32(out.subarray(4, 8 + body.length)), 8 + body.length);
  return out;
};
function writePng(path: string, w: number, h: number, data: Uint8ClampedArray) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr.set([8, 6, 0, 0, 0], 8);
  const raw = Buffer.alloc((w * 4 + 1) * h);
  for (let y = 0; y < h; y++) Buffer.from(data.buffer, data.byteOffset + y * w * 4, w * 4).copy(raw, y * (w * 4 + 1) + 1);
  writeFileSync(path, Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", ihdr), chunk("IDAT", deflateSync(raw, { level: 9 })), chunk("IEND", new Uint8Array())]));
}

if (process.argv[1]?.endsWith("bake-birdie-cutscene.ts")) {
  const W = ARENA_BIRDIE_FALL.w;
  const H = ARENA_BIRDIE_FALL.h;
  if (ARENA_BIRDIE_ARMORED.w !== W || ARENA_BIRDIE_ARMORED.h !== H) throw new Error("the two drawings must be one size");
  const frames = CUTSCENE_ANIMS.flatMap(([ch, a]) => ch.anims[a]!.frames.map((f) => renderFrame(ch, f)));
  const sheet = new Uint8ClampedArray(W * frames.length * H * 4);
  frames.forEach((img, i) => {
    for (let y = 0; y < H; y++) sheet.set(img.data.subarray(y * W * 4, (y + 1) * W * 4), (y * W * frames.length + i * W) * 4);
  });
  writePng(PNG, W * frames.length, H, sheet);
  let col = 0;
  const anims: string[] = [];
  for (const [ch, a] of CUTSCENE_ANIMS) {
    const an = ch.anims[a]!;
    anims.push(`  ${a}: { at: ${col}, ms: [${an.frames.map((f) => f.ms).join(", ")}], loop: ${an.loop}, cues: [${an.frames.map((f) => JSON.stringify(f.cue ?? "")).join(", ")}] },`);
    col += an.frames.length;
  }
  writeFileSync(
    OUT,
    `// Generated by scripts/bake-birdie-cutscene.ts from the cutscene's drawings: don't edit by hand.\n` +
      `/** Birdie's fall's cutscene baked into one picture (birdie-cutscene.png): its frame size, its animations (each's first column, frame times, loop, cues), a hash of its pixels. */\n` +
      `export const BIRDIE_CUTSCENE_SHEET = {\n  w: ${W},\n  h: ${H},\n  frames: ${frames.length},\n  anims: {\n${anims.join("\n")}\n  },\n  hash: "${cutsceneHash()}",\n} as const;\n`,
  );
  console.log(`${PNG}: ${frames.length} frames; ${OUT}`);
}
