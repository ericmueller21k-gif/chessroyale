/**
 * Bakes Jefferson's warehouse crew (packages/app/src/town/shops/grex-crew-art.ts, Eric's approved art, copied as drawn: six
 * giraffes, the scissor lift, the forklift and the loose pallet) into one picture each, as the sidekicks are baked
 * (scripts/bake-sidekicks.ts): `packages/app/src/town/shops/grex-crew/<id>.png`, rows by animation, a frame a column, with what the
 * room needs to play them in `packages/app/src/town/shops/grex-crew-sheets.ts` (both generated; don't edit them by hand).
 *
 * Why (docs/decisions/2026-11-04-jefferson-home.md): painting the crew's parts and drawing their 224 frames as the room loads took
 * about 0.75 s of the page's thread on a computer (measured), three or four times that on a phone, behind the room's fade. Baked, the
 * room loads nine small pictures and cuts them into frames; no crew art code runs in the game. A hash of every frame's pixels is
 * checked against the sprites by `packages/app/test/shop-grex.test.ts`, so a sheet can't go stale. The art's own numbers the room
 * needs (where the pallet rides on the forks, the lift's rise, where each guy steps off) are copied into the generated file with it.
 *
 * Run after changing the crew: `npx tsx scripts/bake-grex-crew.ts`.
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { renderFrame, type Character } from "../packages/app/src/characters/sprite.ts";
import { NPC_GREX, NPC_GREX_CREW_D_SEAT, NPC_GREX_FORK_AT, NPC_GREX_FORK_H, NPC_GREX_RISE, NPC_GREX_STEP_OFF } from "../packages/app/src/town/shops/grex-crew-art.ts";
import { png } from "./bake-sidekicks.ts";

const OUT = "packages/app/src/town/shops/grex-crew-sheets.ts";
const PNGS = "packages/app/src/town/shops/grex-crew";

/** A figure's animations in its sheet's row order (its own order). */
export const crewAnims = (ch: Character): string[] => Object.keys(ch.anims);
/** A hash of a figure's frames' pixels, in its sheet's order (the test recomputes it from the sprite). */
export function crewHash(ch: Character): string {
  const h = createHash("sha256");
  for (const a of crewAnims(ch)) for (const f of ch.anims[a]!.frames) h.update(renderFrame(ch, f).data);
  return h.digest("hex").slice(0, 16);
}

function main() {
  mkdirSync(PNGS, { recursive: true });
  const entries: string[] = [];
  for (const ch of Object.values(NPC_GREX)) {
    const anims = crewAnims(ch);
    const cols = Math.max(...anims.map((a) => ch.anims[a]!.frames.length));
    const W = cols * ch.w;
    const H = anims.length * ch.h;
    const sheet = new Uint8Array(W * H * 4);
    anims.forEach((a, row) =>
      ch.anims[a]!.frames.forEach((f, col) => {
        const { data } = renderFrame(ch, f);
        for (let y = 0; y < ch.h; y++) sheet.set(data.subarray(y * ch.w * 4, (y + 1) * ch.w * 4), ((row * ch.h + y) * W + col * ch.w) * 4);
      }),
    );
    const name = ch.id.replace(/^npc-grex-/, "");
    const pic = png(W, H, sheet);
    writeFileSync(`${PNGS}/${name}.png`, pic);
    const rows = anims
      .map((a, row) => {
        const fr = ch.anims[a]!.frames;
        return `      ${JSON.stringify(a)}: { row: ${row}, loop: ${!!ch.anims[a]!.loop}, ms: [${fr.map((f) => f.ms).join(", ")}], cues: [${fr.map((f) => (f.cue ? JSON.stringify(f.cue) : "null")).join(", ")}] },`;
      })
      .join("\n");
    entries.push(`  ${JSON.stringify(name)}: {\n    id: ${JSON.stringify(ch.id)},\n    w: ${ch.w},\n    h: ${ch.h},\n    foot: [${ch.foot[0]}, ${ch.foot[1]}],\n    anims: {\n${rows}\n    },\n    hash: "${crewHash(ch)}",\n  },`);
    console.log(`${name}: ${W} x ${H}, ${(pic.length / 1024).toFixed(1)} KB`);
  }
  const pts = (list: readonly (readonly [number, number])[]) => `[${list.map((p) => `[${p[0]}, ${p[1]}]`).join(", ")}]`;
  const forkAt = Object.entries(NPC_GREX_FORK_AT)
    .map(([a, list]) => `  ${JSON.stringify(a)}: ${pts(list)},`)
    .join("\n");
  const rise = Object.entries(NPC_GREX_RISE)
    .map(([a, list]) => `  ${JSON.stringify(a)}: [${list.join(", ")}],`)
    .join("\n");
  writeFileSync(
    OUT,
    `// Generated by scripts/bake-grex-crew.ts from packages/app/src/town/shops/grex-crew-art.ts: don't edit by hand
// (npx tsx scripts/bake-grex-crew.ts). Each figure's sheet is ./grex-crew/<name>.png: a row an animation (in \`anims\`' order), a frame
// a column, \`w\` x \`h\` pixels each, drawn 1:1 at the room's scale (37 px a square), facing our right.

/** A baked crew figure: what the room needs to play its sheet's frames. */
export interface CrewSheet {
  /** The sprite's id ("npc-grex-lift"). */
  id: string;
  /** A frame's size, and where its foot stands in it, in pixels. */
  w: number;
  h: number;
  foot: readonly [number, number];
  /** Each animation: its row in the sheet, whether it loops, each frame's time (ms) and cue. */
  anims: Readonly<Record<string, { readonly row: number; readonly loop: boolean; readonly ms: readonly number[]; readonly cues: readonly (string | null)[] }>>;
  /** A hash of every frame's pixels (the test checks it against the sprite). */
  hash: string;
}

export const CREW_SHEETS = {
${entries.join("\n")}
} as const satisfies Record<string, CrewSheet>;
export type CrewName = keyof typeof CREW_SHEETS;

/** Where the pallet's foot goes on the forks, per forklift animation and frame (the forklift's pixels): the art's NPC_GREX_FORK_AT. */
export const CREW_FORK_AT: Readonly<Record<string, readonly (readonly [number, number])[]>> = {
${forkAt}
};
/** The lift's platform rise per frame of \`up\`, \`upIdle\` and \`down\` (px): the art's NPC_GREX_RISE. */
export const CREW_RISE: Readonly<Record<string, readonly number[]>> = {
${rise}
};
/** Where each guy stands once off his machine, from its foot (px; y south): the art's NPC_GREX_STEP_OFF. */
export const CREW_STEP_OFF = { lift: [${NPC_GREX_STEP_OFF.lift.join(", ")}], forklift: [${NPC_GREX_STEP_OFF.forklift.join(", ")}] } as const;
/** The forks' heights (px over the ground): the art's NPC_GREX_FORK_H. */
export const CREW_FORK_H = ${JSON.stringify(NPC_GREX_FORK_H).replace(/"(\w+)":/g, "$1: ").replace(/,/g, ", ")} as const;
/** The dozer's seat on his pallet (px): the art's NPC_GREX_CREW_D_SEAT. */
export const CREW_D_SEAT = ${NPC_GREX_CREW_D_SEAT};
`,
  );
}

if (process.argv[1]?.endsWith("bake-grex-crew.ts")) main();
